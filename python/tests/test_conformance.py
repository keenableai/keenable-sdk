@pytest.mark.parametrize("kind", CLIENTS)
@pytest.mark.parametrize("case", cases("retry"))
async def test_retry(kind: str, case: dict[str, Any], waits: list[float]) -> None:
    outcome = await run(
        kind,
        [reply(case), SEARCH_OK],
        waits,
        options={"max_retries": case["max_retries"]},
    )
    if case["retried"]:
        assert outcome.error is None
        assert len(outcome.requests) == 2
        assert len(outcome.waits) == 1
        if case["wait"] == "backoff":
            assert 0.375 <= outcome.waits[0] <= 0.5
        else:
            assert outcome.waits[0] == pytest.approx(case["wait"])
    else:
        assert len(outcome.requests) == 1
        assert outcome.waits == []
        if case["kind"] == "redirect":
            assert isinstance(outcome.error, KeenableConnectionError)
            assert not isinstance(outcome.error, KeenableTimeoutError)
            assert "redirect" in str(outcome.error)
        else:
            assert type(outcome.error) is KINDS[case["kind"]]


# --- error and success bodies ------------------------------------------------


def _visible(error: KeenableAPIError) -> str:
    """Everything an error shows except ``body`` and ``fix``, the API's text."""
    fields = {k: v for k, v in vars(error).items() if k not in ("body", "fix")}
    return f"{error} {error.args!r} {fields!r}"


@pytest.mark.parametrize("kind", CLIENTS)
@pytest.mark.parametrize("case", cases("errors"))
async def test_errors(kind: str, case: dict[str, Any], waits: list[float]) -> None:
    outcome = await run(kind, [reply(case)], waits, options={"max_retries": 0})
    error = outcome.error
    want = case["expect"]
    assert type(error) is KINDS[want["kind"]]
    assert isinstance(error, KeenableAPIError)
    assert error.status_code == case["status"]
    got = {
        "detail": error.body,
        "code": error.code,
        "type": error.type,
        "error": error.error,
        "fix": error.fix,
        "retryable": error.retryable,
        "retry_after_seconds": error.retry_after_seconds,
        "request_id": error.request_id,
        "param": error.param,
        "value": error.value,
        "reason": error.reason,
        "limit": dataclasses.asdict(error.limit) if error.limit else None,
    }
    assert got == {key: want[key] for key in got}
    message = str(error)
    for text in want["message_contains"]:
        assert text in message
    for text in want["message_excludes"]:
        assert text not in message
    for text in want["absent"]:
        assert text not in _visible(error)


