SEARCH_OK = (200, {}, b'{"results": []}')
PAGE_OK = (200, {}, b'{"results": [{"content": "c"}]}')

# One reply: status, headers and the body bytes.
Reply = tuple[int, dict[str, str], bytes]


def cases(section: str) -> Any:
    """A section's cases as pytest params, named, without Python's skips."""
    items = FIXTURE[section]
    if isinstance(items, dict):
        items = items["cases"]
    return [
        pytest.param(case, id=case["name"])
        for case in items
        if "python" not in case.get("skip", {})
    ]


def reply(case: dict[str, Any]) -> Reply:
    return (case["status"], case["headers"], case["body"].encode("utf-8"))


def value(raw: Any) -> Any:
    """A fixture value, with {"$float": "NaN"} read as the float it names."""
    if isinstance(raw, dict) and set(raw) == {"$float"}:
        return float(raw["$float"])
    return raw


class Outcome:
    def __init__(self) -> None:
        self.result: Any = None
        self.error: KeenableError | None = None
        self.requests: list[httpx.Request] = []
        self.waits: list[float] = []


@pytest.fixture
def waits(monkeypatch: pytest.MonkeyPatch) -> list[float]:
    """Record the waits between attempts instead of sleeping through them."""
    recorded: list[float] = []
    monkeypatch.setattr(client_module.time, "sleep", recorded.append)

    async def fake_sleep(delay: float) -> None:
        recorded.append(delay)

    monkeypatch.setattr(client_module.asyncio, "sleep", fake_sleep)
    monkeypatch.delenv("KEENABLE_API_URL", raising=False)
    return recorded


async def run(
    kind: str,
    replies: list[Reply],
    waits: list[float],
    *,
    method: str = "search",
    arg: Any = "q",
    options: dict[str, Any] | None = None,
    call: dict[str, Any] | None = None,
) -> Outcome:
    """Call ``method(arg)`` on a client whose attempt n gets ``replies[n]``."""
    outcome = Outcome()
    outcome.waits = waits

    def handler(request: httpx.Request) -> httpx.Response:
        outcome.requests.append(request)
        status, headers, body = replies[min(len(outcome.requests), len(replies)) - 1]
        return httpx.Response(status, headers=headers, content=body)

    transport = httpx.MockTransport(handler)
    settings = {"api_key": "k", **(options or {})}
    try:
        if kind == "sync":
            with Keenable(client=httpx.Client(transport=transport), **settings) as c:
                outcome.result = getattr(c, method)(arg, **(call or {}))
        else:
            async with AsyncKeenable(
                client=httpx.AsyncClient(transport=transport), **settings
            ) as ac:
                outcome.result = await getattr(ac, method)(arg, **(call or {}))
    except KeenableError as error:
        outcome.error = error
    return outcome


